// World geometry. Coastlines are stored as [longitude, latitude] pairs and
// projected at render time, which is far easier to reason about (and correct)
// than hand-written SVG path data in screen pixels.
//
// Simplified on purpose: enough outline to read as the real world at a glance,
// not a cartographic dataset.

export const PROJECTION = { width: 1000, height: 500 };

/** Equirectangular projection: lon/lat → SVG units. */
export function project([lon, lat]) {
  return [
    ((lon + 180) / 360) * PROJECTION.width,
    ((90 - lat) / 180) * PROJECTION.height,
  ];
}

/** Turn a ring of lon/lat pairs into an SVG path. */
export function ringToPath(ring) {
  return (
    ring
      .map((point, i) => {
        const [x, y] = project(point);
        return `${i === 0 ? 'M' : 'L'}${x.toFixed(1)},${y.toFixed(1)}`;
      })
      .join('') + 'Z'
  );
}

